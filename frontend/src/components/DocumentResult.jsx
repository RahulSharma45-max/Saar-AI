import React, { useState } from 'react';
import { 
  FileText, 
  Sparkles, 
  Lightbulb, 
  CheckSquare, 
  FileCode, 
  CheckCircle2, 
  Download,
  BookOpen,
  ArrowUpRight
} from 'lucide-react';
import SummaryCard from './SummaryCard';
import KeyPoints from './KeyPoints';
import Suggestions from './Suggestions';
import ExtractedText from './ExtractedText';

/**
 * DocumentResult Component
 * Follows section 5 specification:
 * - Rendered below the upload section and submit button
 * - White card with rounded corners (12-16px) and subtle shadow
 * - Heading: "Processing Results" with small success badge
 * - Displays the actual response generated by the existing backend
 * - Preserves all existing result fields, formatting, tabs, and export
 * - Scrollable and readable typography
 */
export default function DocumentResult({ result, onBackToUpload }) {
  const [activeTab, setActiveTab] = useState('overview');

  if (!result) return null;

  const {
    fileName = 'document.pdf',
    extractedText = '',
    summaryLength = 'MEDIUM',
    summary = '',
    keyPoints = [],
    improvementSuggestions = [],
    pageCount,
  } = result;

  const isPdf = fileName.toLowerCase().endsWith('.pdf');
  const wordCount = extractedText.trim() ? extractedText.trim().split(/\s+/).length : 0;
  const summaryWordCount = summary.trim() ? summary.trim().split(/\s+/).length : 0;
  const compressionRatio = wordCount > 0 ? Math.round((1 - (summaryWordCount / wordCount)) * 100) : 0;

  const tabs = [
    { id: 'overview', label: 'Overview', icon: BookOpen, count: null },
    { id: 'summary', label: 'AI Summary', icon: Sparkles, count: `${summaryLength}` },
    { id: 'keyPoints', label: 'Key Points', icon: Lightbulb, count: keyPoints.length },
    { id: 'suggestions', label: 'Suggestions', icon: CheckSquare, count: improvementSuggestions.length },
    { id: 'extractedText', label: 'Extracted Text', icon: FileCode, count: `${wordCount}w` },
  ];

  const handleExportText = () => {
    const content = `SaarAI Analysis Report\nDocument: ${fileName}\nDate: ${new Date().toLocaleString()}\n\n--- SUMMARY (${summaryLength}) ---\n${summary}\n\n--- KEY POINTS ---\n${keyPoints.map((p, i) => `${i + 1}. ${p}`).join('\n')}\n\n--- SUGGESTIONS ---\n${improvementSuggestions.map((s, i) => `${i + 1}. ${s}`).join('\n')}\n\n--- EXTRACTED TEXT ---\n${extractedText}`;
    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${fileName.replace(/\.[^/.]+$/, "")}_SaarAI_Summary.txt`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <section className="card results-card-main" id="results-section" aria-label="Processing Results">
      {/* Top Header of Results Card */}
      <div className="results-header-row">
        <div className="results-title-group">
          <div className="results-badge-row">
            <span className="success-badge">
              <CheckCircle2 size={14} className="success-badge-icon" />
              <span>Processing Succeeded</span>
            </span>
            <span className="doc-pill">
              {isPdf ? 'PDF Document' : 'Image OCR'}
            </span>
            {pageCount && (
              <span className="doc-pill">
                {pageCount} {pageCount === 1 ? 'Page' : 'Pages'}
              </span>
            )}
          </div>
          <h2 className="results-main-title">Processing Results</h2>
          <p className="results-filename-text" title={fileName}>
            Analysis output for <strong className="filename-bold">{fileName}</strong>
          </p>
        </div>

        <div className="results-actions-group">
          <button 
            type="button" 
            className="btn btn-export-report"
            onClick={handleExportText}
            title="Download complete summary report"
          >
            <Download size={15} />
            <span>Export Report</span>
          </button>
        </div>
      </div>

      {/* Quick Statistics Strip */}
      <div className="results-metrics-strip">
        <div className="metric-cell">
          <span className="metric-label">Extracted Words</span>
          <span className="metric-value">{wordCount.toLocaleString()}</span>
        </div>
        <div className="metric-divider" />
        <div className="metric-cell">
          <span className="metric-label">Summary Words</span>
          <span className="metric-value">{summaryWordCount.toLocaleString()}</span>
        </div>
        <div className="metric-divider" />
        <div className="metric-cell">
          <span className="metric-label">Condensation</span>
          <span className="metric-value highlight-accent">{compressionRatio > 0 ? `${compressionRatio}%` : 'N/A'}</span>
        </div>
        <div className="metric-divider" />
        <div className="metric-cell">
          <span className="metric-label">Key Points</span>
          <span className="metric-value">{keyPoints.length}</span>
        </div>
      </div>

      {/* Tabs Navigation */}
      <div className="results-tabs-bar" role="tablist">
        {tabs.map((tab) => {
          const Icon = tab.icon;
          const isActive = activeTab === tab.id;
          return (
            <button
              key={tab.id}
              role="tab"
              aria-selected={isActive}
              type="button"
              className={`results-tab-pill ${isActive ? 'is-active' : ''}`}
              onClick={() => setActiveTab(tab.id)}
            >
              <Icon size={15} className="tab-pill-icon" />
              <span className="tab-pill-label">{tab.label}</span>
              {tab.count !== null && (
                <span className="tab-pill-count">{tab.count}</span>
              )}
            </button>
          );
        })}
      </div>

      {/* Tab Panels with existing components preserved */}
      <div className="results-tab-body">
        {activeTab === 'overview' && (
          <div className="results-overview-container">
            <SummaryCard summary={summary} summaryLength={summaryLength} />
            <div className="overview-two-col-grid">
              <KeyPoints keyPoints={keyPoints} />
              <Suggestions suggestions={improvementSuggestions} />
            </div>
          </div>
        )}

        {activeTab === 'summary' && (
          <div className="results-pane-single">
            <SummaryCard summary={summary} summaryLength={summaryLength} />
          </div>
        )}

        {activeTab === 'keyPoints' && (
          <div className="results-pane-single">
            <KeyPoints keyPoints={keyPoints} />
          </div>
        )}

        {activeTab === 'suggestions' && (
          <div className="results-pane-single">
            <Suggestions suggestions={improvementSuggestions} />
          </div>
        )}

        {activeTab === 'extractedText' && (
          <div className="results-pane-single">
            <ExtractedText text={extractedText} fileName={fileName} />
          </div>
        )}
      </div>
    </section>
  );
}
